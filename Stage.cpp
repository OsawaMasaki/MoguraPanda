void Stage::Draw()
{
	// ステージの描画
	for (int y = 0; y < STAGE_HEIGHT; y++)
	{
		for (int x = 0; x < STAGE_WIDTH; x++)
		{
			DrawBox(x * CHA_SIZE, y * CHA_SIZE, (x + 1) * CHA_SIZE, (y + 1) * CHA_SIZE, GetColor(150, 250,150), FALSE);
			if (stageData[y][x] == 1)
			{
				DrawBox(x * CHA_SIZE, y * CHA_SIZE, (x + 1) * CHA_SIZE, (y + 1) * CHA_SIZE, GetColor(182,82,51), TRUE);
			}
		}
	}
}

int Stage::GetMap(int x, int y)
{
	return stageData[y][x];
}
